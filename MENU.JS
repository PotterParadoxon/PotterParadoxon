(function (app) {

  /*
   * ============================================================
   * ROBCO BOTTLE CAP-FLIP
   * MENU.JS
   * ============================================================
   *
   * Hauptmenü
   *
   * NEUES SPIEL
   * STATISTIK
   * OPTIONEN
   *
   * Keine Auswahl-Rechtecke.
   * Die Auswahl wird mit > TEXT < dargestellt.
   *
   * ============================================================
   */


  // ============================================================
  // AUSWAHL
  // ============================================================

  let selected = 0;


  // ============================================================
  // MENÜEINTRÄGE
  // ============================================================

  const items = [

    'newGame',

    'statistics',

    'settings'

  ];


  // ============================================================
  // TEXT-FUNKTIONEN
  // ============================================================

  function centerText(text, x, y) {

    h.setFontAlign(
      0,
      0
    );

    h.drawString(
      text,
      x,
      y
    );

  }


  function leftText(text, x, y) {

    h.setFontAlign(
      -1,
      0
    );

    h.drawString(
      text,
      x,
      y
    );

  }


  function rightText(text, x, y) {

    h.setFontAlign(
      1,
      0
    );

    h.drawString(
      text,
      x,
      y
    );

  }


  // ============================================================
  // MENÜ ZEICHNEN
  // ============================================================

  function drawMenu() {

    h.reset().clear();

    h.setColor(3);


    // ==========================================================
    // ROBCO HEADER
    // ==========================================================

    h.setFont(
      'Monofonto23'
    );

    centerText(
      app.text('robco'),
      240,
      25
    );


    // ==========================================================
    // TERMINAL UNTERTITEL
    // ==========================================================

    h.setFont(
      'Monofonto14'
    );

    centerText(
      'C-FLIP TERMINAL SYSTEM',
      240,
      48
    );


    // ==========================================================
    // TRENNLINIE
    // ==========================================================

    h.drawLine(
      25,
      63,
      455,
      63
    );


    // ==========================================================
    // TERMINAL STATUS
    // ==========================================================

    h.setFont(
      'Monofonto14'
    );

    leftText(
      'ROBCO INDUSTRIES',
      30,
      82
    );

    rightText(
      'TERMLINK',
      450,
      82
    );


    // ==========================================================
    // MENÜTITEL
    // ==========================================================

    h.setFont(
      'Monofonto18'
    );

    centerText(
      app.text('cflip'),
      240,
      112
    );


    // ==========================================================
    // PROGRAMMAUSWAHL
    // ==========================================================

    h.setFont(
      'Monofonto14'
    );

    centerText(
      'SELECT PROGRAM',
      240,
      134
    );


    // ==========================================================
    // MENÜPOSITIONEN
    // ==========================================================

    const menuY = [

      170,

      205,

      240

    ];


    // ==========================================================
    // MENÜ ZEICHNEN
    // ==========================================================

    for (
      let i = 0;
      i < items.length;
      i++
    ) {

      h.setFont(
        'Monofonto18'
      );


      if (
        i === selected
      ) {

        centerText(
          '> ' +
          app.text(
            items[i]
          ) +
          ' <',
          240,
          menuY[i]
        );

      } else {

        centerText(
          app.text(
            items[i]
          ),
          240,
          menuY[i]
        );

      }

    }


    // ==========================================================
    // UNTERE TRENNLINIE
    // ==========================================================

    h.drawLine(
      25,
      263,
      455,
      263
    );


    // ==========================================================
    // ROBCO STATUSZEILE
    // ==========================================================

    h.setFont(
      'Monofonto14'
    );

    leftText(
      app.text('robco'),
      30,
      282
    );

    rightText(
      'RCBCF-TERM',
      450,
      282
    );


    // ==========================================================
    // SYSTEM STATUS
    // ==========================================================

    centerText(
      app.text('systemReady'),
      240,
      305
    );


    // ==========================================================
    // DISPLAY AKTUALISIEREN
    // ==========================================================

    h.flip();

    Pip.lastFlip =
      getTime();

  }


  // ============================================================
  // KNOB 1
  // ============================================================

  function onKnob1(dir) {


    // ==========================================================
    // KNOB DREHEN
    // ==========================================================

    if (dir !== 0) {

      selected += dir;


      // --------------------------------------------------------
      // ÜBERLAUF NACH UNTEN
      // --------------------------------------------------------

      if (
        selected >=
        items.length
      ) {

        selected = 0;

      }


      // --------------------------------------------------------
      // ÜBERLAUF NACH OBEN
      // --------------------------------------------------------

      if (
        selected < 0
      ) {

        selected =
          items.length - 1;

      }


      drawMenu();

      return;

    }


    // ==========================================================
    // KNOB DRÜCKEN
    // ==========================================================

    switch (selected) {


      // ========================================================
      // NEUES SPIEL
      // ========================================================

      case 0:

        app.go(
          app.scenes.GAME
        );

        return;


      // ========================================================
      // STATISTIK
      // ========================================================

      case 1:

        app.go(
          app.scenes.STATS
        );

        return;


      // ========================================================
      // OPTIONEN
      // ========================================================

      case 2:

        app.go(
          app.scenes.SETTINGS
        );

        return;

    }

  }


  // ============================================================
  // KNOB EVENT
  // ============================================================
  //
  // Bewusst Pip.on() statt Pip.onExclusive().
  //
  // Dadurch bleibt der Szenenwechsel kompatibel mit GAME.JS,
  // STATISTIC.JS und SETTINGS.JS.
  //
  // ============================================================

  Pip.on(
    'knob1',
    onKnob1
  );


  // ============================================================
  // INITIAL DISPLAY
  // ============================================================

  drawMenu();


  // ============================================================
  // CLEANUP
  // ============================================================

  return {

    remove: function () {

      try {

        Pip.removeListener(
          'knob1',
          onKnob1
        );

      } catch (e) {}


      h.reset().clear();

      h.flip();

    }

  };


});